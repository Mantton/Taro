use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use compiler::error::ReportedError;

use crate::{
    TestArgs,
    command::{CommandOutcome, CommandResult, build, child_exit_code, doctest},
};

pub fn run(arguments: TestArgs) -> CommandResult {
    if arguments.doc {
        return doctest::run(arguments);
    }
    if let Some(target_name) = arguments.fuzz.clone() {
        return run_fuzz(arguments, &target_name);
    }
    let coverage = arguments.coverage;
    let exe = build::run_test_mode(arguments)?;
    let exe = exe.ok_or_else(|| {
        eprintln!("error: no test executable was produced");
        ReportedError
    })?;

    if !coverage {
        let status = Command::new(&exe).status().map_err(|e| {
            eprintln!("error: failed to execute '{}': {}", exe.display(), e);
            ReportedError
        })?;

        return if status.success() {
            Ok(CommandOutcome::Success)
        } else {
            Ok(CommandOutcome::ChildExit(child_exit_code(status)))
        };
    }

    run_with_coverage(&exe)
}

fn run_fuzz(arguments: TestArgs, target_name: &str) -> CommandResult {
    let target_path_display = arguments.common.path.display().to_string();
    let fuzz_runs = arguments.fuzz_runs;
    let fuzz_seed = arguments.fuzz_seed;
    let fuzz_max_len = arguments.fuzz_max_len;
    let fuzz_replay = arguments.fuzz_replay;

    let exe = build::run_fuzz_mode(arguments.common, target_name)?;
    let exe = exe.ok_or_else(|| {
        eprintln!("error: no fuzz executable was produced");
        ReportedError
    })?;

    let artifacts_dir = exe
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join("fuzz-artifacts");

    let mut cmd = Command::new(&exe);
    cmd.env("TARO_FUZZ_ARTIFACTS_DIR", &artifacts_dir);
    cmd.env("TARO_FUZZ_TARGET_PATH", &target_path_display);
    if let Some(runs) = fuzz_runs {
        cmd.env("TARO_FUZZ_RUNS", runs.to_string());
    }
    if let Some(seed) = fuzz_seed {
        cmd.env("TARO_FUZZ_SEED", seed.to_string());
    }
    if let Some(max_len) = fuzz_max_len {
        cmd.env("TARO_FUZZ_MAX_LEN", max_len.to_string());
    }
    if let Some(replay) = fuzz_replay {
        cmd.env("TARO_FUZZ_REPLAY", replay);
    }

    let status = cmd.status().map_err(|e| {
        eprintln!("error: failed to execute '{}': {}", exe.display(), e);
        ReportedError
    })?;

    if status.success() {
        Ok(CommandOutcome::Success)
    } else {
        Ok(CommandOutcome::ChildExit(child_exit_code(status)))
    }
}

fn run_with_coverage(exe: &Path) -> CommandResult {
    let coverage_dir = exe
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join("coverage");
    fs::create_dir_all(&coverage_dir).map_err(|e| {
        eprintln!(
            "error: failed to create coverage output directory '{}': {}",
            coverage_dir.display(),
            e
        );
        ReportedError
    })?;

    let stem = exe
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("test");
    let profraw = coverage_dir.join(format!("{stem}.profraw"));
    let profdata = coverage_dir.join(format!("{stem}.profdata"));
    let _ = fs::remove_file(&profraw);
    let _ = fs::remove_file(&profdata);

    let status = Command::new(exe)
        .env("LLVM_PROFILE_FILE", &profraw)
        .status()
        .map_err(|e| {
            eprintln!("error: failed to execute '{}': {}", exe.display(), e);
            ReportedError
        })?;

    if !status.success() {
        return Ok(CommandOutcome::ChildExit(child_exit_code(status)));
    }

    if !profraw.exists() {
        eprintln!(
            "error: coverage profile '{}' was not generated by '{}'; ensure the binary was built and linked with --coverage",
            profraw.display(),
            exe.display()
        );
        return Err(ReportedError);
    }

    let profdata_tool = resolve_llvm_tool("llvm-profdata", "TARO_LLVM_PROFDATA")?;
    let cov_tool = resolve_llvm_tool("llvm-cov", "TARO_LLVM_COV")?;

    let merge_output = Command::new(&profdata_tool)
        .arg("merge")
        .arg("-sparse")
        .arg(&profraw)
        .arg("-o")
        .arg(&profdata)
        .output()
        .map_err(|e| {
            eprintln!(
                "error: failed to invoke '{}' to merge coverage data: {}",
                profdata_tool.display(),
                e
            );
            ReportedError
        })?;
    if !merge_output.status.success() {
        let stderr = String::from_utf8_lossy(&merge_output.stderr);
        eprintln!(
            "error: '{}' failed to merge '{}' into '{}' (exit {}): {}",
            profdata_tool.display(),
            profraw.display(),
            profdata.display(),
            child_exit_code(merge_output.status),
            stderr.trim()
        );
        return Err(ReportedError);
    }

    let report_output = Command::new(&cov_tool)
        .arg("report")
        .arg(exe)
        .arg(format!("-instr-profile={}", profdata.display()))
        .output()
        .map_err(|e| {
            eprintln!(
                "error: failed to invoke '{}' to render coverage report: {}",
                cov_tool.display(),
                e
            );
            ReportedError
        })?;
    if !report_output.status.success() {
        let stderr = String::from_utf8_lossy(&report_output.stderr);
        eprintln!(
            "error: '{}' failed to report coverage for '{}' (exit {}): {}",
            cov_tool.display(),
            exe.display(),
            child_exit_code(report_output.status),
            stderr.trim()
        );
        return Err(ReportedError);
    }

    let report_text = String::from_utf8_lossy(&report_output.stdout);
    print!("{report_text}");
    println!("coverage profile: {}", profdata.display());

    Ok(CommandOutcome::Success)
}

fn resolve_llvm_tool(tool_name: &str, env_var: &str) -> Result<PathBuf, ReportedError> {
    if let Ok(explicit) = std::env::var(env_var) {
        let trimmed = explicit.trim();
        if !trimmed.is_empty() {
            let candidate = PathBuf::from(trimmed);
            if is_executable_tool(&candidate) {
                return Ok(candidate);
            }
            eprintln!(
                "error: {env_var} points to '{}', which is not executable; install '{tool_name}' or fix {env_var}",
                candidate.display()
            );
            return Err(ReportedError);
        }
    }

    if let Some(found) = find_in_path(tool_name) {
        return Ok(found);
    }

    for dir in [
        "/opt/homebrew/opt/llvm@22/bin",
        "/opt/homebrew/opt/llvm/bin",
        "/usr/local/opt/llvm@22/bin",
        "/usr/local/opt/llvm/bin",
    ] {
        let candidate = Path::new(dir).join(tool_name);
        if is_executable_tool(&candidate) {
            return Ok(candidate);
        }
    }

    #[cfg(target_os = "macos")]
    {
        if let Ok(output) = Command::new("xcrun").args(["--find", tool_name]).output() {
            if output.status.success() {
                let raw = String::from_utf8_lossy(&output.stdout);
                let path = PathBuf::from(raw.trim());
                if is_executable_tool(&path) {
                    return Ok(path);
                }
            }
        }
    }

    eprintln!(
        "error: source coverage requires '{tool_name}', which was not found; install LLVM tools, add '{tool_name}' to PATH, or set {env_var}"
    );
    Err(ReportedError)
}

fn find_in_path(tool_name: &str) -> Option<PathBuf> {
    let path_var = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path_var) {
        let candidate = dir.join(tool_name);
        if is_executable_tool(&candidate) {
            return Some(candidate);
        }
    }
    None
}

fn is_executable_tool(path: &Path) -> bool {
    let Ok(meta) = fs::metadata(path) else {
        return false;
    };
    if !meta.is_file() {
        return false;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        meta.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        true
    }
}

#[cfg(test)]
mod tests {
    use super::resolve_llvm_tool;

    #[test]
    fn explicit_env_override_rejects_missing_tool_with_error() {
        let key = "TARO_TEST_MISSING_LLVM_TOOL_OVERRIDE";
        unsafe {
            std::env::set_var(key, "/nonexistent/taro/missing-llvm-cov");
        }
        let result = resolve_llvm_tool("llvm-cov", key);
        unsafe {
            std::env::remove_var(key);
        }
        assert!(result.is_err());
    }
}
